#Пользователь вводит стороны прямоугольника, выведите его площадь и периметр. На вход программе могут подаваться как целые числа, так и вещественные

# Запрашиваем у пользователя стороны прямоугольника
try:
    a = float(input("Введите длину первой стороны: "))
    b = float(input("Введите длину второй стороны: "))

    # Проверка на положительность сторон
    if a <= 0 or b <= 0:
        print("Ошибка: стороны должны быть положительными числами!")
    else:
        # Вычисляем площадь и периметр
        area = a * b
        perimeter = 2 * (a + b)

        # Выводим результат
        print(f"Площадь прямоугольника: {area}")
        print(f"Периметр прямоугольника: {perimeter}")

except ValueError:
    print("Ошибка: пожалуйста, введите числа (целые или вещественные)!")



#Задание №2

#Дано пятизначное целое число. Напишите алгоритм, который возведёт количество десятков в степень количества единиц. Затем умножит это число на количество сотен. И делит получившееся число на разность количества десятков тысяч и количества тысяч

# Вводим пятизначное число
try:
    num = int(input("Введите пятизначное целое число: "))

    # Проверяем, что число пятизначное
    if 10000 <= abs(num) <= 99999:

        # Извлекаем цифры числа
        # Для отрицательных чисел используем abs()
        n = abs(num)

        desyatki_tysyach = n // 10000  # десятки тысяч
        tysyachi = (n // 1000) % 10  # тысячи
        sotni = (n // 100) % 10  # сотни
        desyatki = (n // 10) % 10  # десятки
        edinitsy = n % 10  # единицы

        # Выполняем вычисления по условию
        # 1) Возводим количество десятков в степень количества единиц
        stepen = desyatki ** edinitsy

        # 2) Умножаем на количество сотен
        proizvedenie = stepen * sotni

        # 3) Делим на разность десятков тысяч и тысяч
        raznost = desyatki_tysyach - tysyachi
        result = proizvedenie / raznost

        # Выводим результат
        print(f"Результат: {result}")
        print(f"(Проверка: {desyatki}^{edinitsy} * {sotni} / ({desyatki_tysyach} - {tysyachi}) = {result})")

    else:
        print("Ошибка: число должно быть пятизначным!")

except ValueError:
    print("Ошибка: пожалуйста, введите целое число!")