print("=" * 50)
print("Задание №1: Перевернуть массив")
print("=" * 50)

# Вводим количество чисел
N = int(input("Введите количество чисел: "))

# Вводим N чисел
numbers = []
for i in range(N):
    num = int(input(f"Введите число {i + 1}: "))
    numbers.append(num)

# Переворачиваем и выводим
reversed_numbers = numbers[::-1]
print("Перевернутый массив:")
for num in reversed_numbers:
    print(num)

print("\n" + "=" * 50)

