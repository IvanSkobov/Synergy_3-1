# Задание №2 - Изменение массива по правилу
# ============================================

print("Задание №2: Изменение массива по правилу")
print("=" * 50)

# Вводим количество чисел
N2 = int(input("Введите количество чисел: "))

# Вводим N чисел через пробел
# Важно: используем try-except для обработки пустого ввода
try:
    numbers2 = list(map(int, input("Введите числа через пробел: ").split()))

    # Проверяем, что ввели ровно N чисел
    if len(numbers2) != N2:
        print(f"Ошибка: введите ровно {N2} чисел!")
    else:
        # Выполняем преобразование
        result = []
        left = 0
        right = N2 - 1

        while left <= right:
            if left == right:
                result.append(numbers2[left])
            else:
                result.append(numbers2[right])
                result.append(numbers2[left])
            left += 1
            right -= 1

        print("Измененный массив:")
        print(*result)

except ValueError:
    print("Ошибка: введите числа через пробел!")

print("\n" + "=" * 50)

