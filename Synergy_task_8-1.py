print("Задание №3: Рыбаки и лодки")
print("=" * 50)

# Вводим грузоподъёмность лодки
m = int(input("Введите грузоподъёмность лодки (m): "))

# Вводим количество рыбаков
n = int(input("Введите количество рыбаков (n): "))

# Вводим веса рыбаков
weights = []
for i in range(n):
    weight = int(input(f"Вес рыбака {i + 1}: "))
    weights.append(weight)

# Сортируем веса
weights.sort()

# Вычисляем минимальное количество лодок
left = 0
right = n - 1
boats = 0

while left <= right:
    if weights[left] + weights[right] <= m:
        left += 1
    right -= 1
    boats += 1

print(f"Минимальное количество лодок: {boats}")

print("\n" + "=" * 50)
print("Все задания выполнены!")