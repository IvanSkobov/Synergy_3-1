pet_name = input("Введите кличку питомца: ")

# Определяем правильное окончание для возраста
age_word = get_age_word(pet_age)

# Выводим результат
print(f"Это {pet_type} по кличке \"{pet_name}\". Возраст: {pet_age} {age_word}.")



