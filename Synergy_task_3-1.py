def get_age_word(age):
    """Возвращает правильное склонение слова 'год' для возраста"""
    age = int(age)
    if 11 <= age % 100 <= 19:
        return "лет"
    elif age % 10 == 1:
        return "год"
    elif 2 <= age % 10 <= 4:
        return "года"
    else:
        return "лет"

